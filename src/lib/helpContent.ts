/** Normalize Arabic text for forgiving search (strip tashkeel, unify alef/ya/ta-marbuta). */
export function normalizeHelpText(s: string): string {
  return s
    .toLowerCase()
    .replace(/[ً-ْ]/g, "") // tashkeel
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/ـ/g, "")
    .replace(/[^a-z0-9\u0600-\u06ff]+/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
}

