const STOP_WORDS = new Set([
  "ازاي", "كيف", "اعمل", "ممكن", "عايز", "عايزه", "ليه", "ايه", "هو", "هي",
  "في", "من", "علي", "عن", "لو", "انا", "ال", "و", "او", "ده", "دي",
]);

const NORMALIZED_ALIAS_GROUPS = SEARCH_ALIASES.map((group) =>
  group.map((term) => normalizeHelpText(term)),
);

function editDistanceAtMostOne(a: string, b: string): boolean {
  if (a === b) return true;
  if (Math.abs(a.length - b.length) > 1) return false;
  let i = 0;
  let j = 0;
  let edits = 0;
  while (i < a.length && j < b.length) {
    if (a[i] === b[j]) {
      i += 1;
      j += 1;
      continue;
    }
    edits += 1;
    if (edits > 1) return false;
    if (a.length > b.length) i += 1;
    else if (b.length > a.length) j += 1;
    else {
      i += 1;
      j += 1;
    }
  }
  return edits + Number(i < a.length || j < b.length) <= 1;
}

function expandedTerms(token: string): string[] {
  const group = NORMALIZED_ALIAS_GROUPS.find((items) =>
    items.some((item) => item === token || item.split(" ").includes(token)),
  );
  return group ? [...new Set([token, ...group])] : [token];
}

function tokenScore(token: string, corpus: string, words: string[]): number {
  const aliases = expandedTerms(token);
  if (aliases.some((alias) => corpus.includes(alias))) return aliases[0] === token ? 12 : 8;
  if (token.length >= 4 && words.some((word) => word.length >= 4 && editDistanceAtMostOne(token, word))) return 4;
  return 0;
}

/**
 * Filter sections by a free-text query against question + answer. Returns only
 * sections that have at least one matching item, each narrowed to its matches.
 * An empty/whitespace query returns the input unchanged.
 */
export function searchHelp(sections: HelpSection[], query: string): HelpSection[] {
  const q = normalizeHelpText(query);
  if (!q) return sections;
  const queryTokens = q.split(" ").filter((token) => token.length > 1 && !STOP_WORDS.has(token));
  const ranked: Array<{ section: HelpSection; score: number }> = [];
  for (const section of sections) {
    const normalizedTitle = normalizeHelpText(section.title);
    const titleMatches = normalizedTitle.includes(q) || queryTokens.every((token) => tokenScore(token, normalizedTitle, normalizedTitle.split(" ")) > 0);
    if (titleMatches) {
      ranked.push({ section, score: 200 });
      continue;
    }

    const scoredItems = section.items
      .map((item) => {
        const question = normalizeHelpText(item.q);
        const corpus = normalizeHelpText(`${item.q} ${item.a} ${(item.keywords ?? []).join(" ")}`);
        const words = corpus.split(" ");
        const exact = question.includes(q) ? 100 : corpus.includes(q) ? 70 : 0;
        const scores = queryTokens.map((token) => tokenScore(token, corpus, words));
        const matchedTokens = scores.filter((score) => score > 0).length;
        const requiredMatches = queryTokens.length <= 2 ? queryTokens.length : Math.ceil(queryTokens.length * 0.6);
        const score = exact + scores.reduce((sum, value) => sum + value, 0);
        return { item, score, matchedTokens, requiredMatches };
      })
      .filter((row) => row.score > 0 && row.matchedTokens >= row.requiredMatches)
      .sort((a, b) => b.score - a.score);

    if (scoredItems.length > 0) {
      ranked.push({
        section: { ...section, items: scoredItems.map((row) => row.item) },
        score: scoredItems[0]!.score,
      });
    }
  }
  return ranked.sort((a, b) => b.score - a.score).map((row) => row.section);
}
