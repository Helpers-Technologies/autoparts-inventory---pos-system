/** Folds the spelling variants Egyptian addresses are typed with (أ/إ/آ → ا,
 *  ة → ه, ى → ي) so a saved address still matches a list entry. */
export function normalizePlaceName(value?: string): string {
  return (value ?? "")
    .trim()
    .toLocaleLowerCase()
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[\s_-]+/g, " ");
}

/** The canonical governorate name for a typed or imported value, or "" when
 *  it matches nothing known. */
export function matchGovernorate(value?: string): string {
  const wanted = normalizePlaceName(value);
  if (!wanted) return "";
  return (
    EGYPT_GOVERNORATES.find((name) => normalizePlaceName(name) === wanted) ?? ""
  );
}

/** Known cities / marakez for a governorate. Empty for an unknown one — the
 *  city field stays free-text rather than blocking. */
export function citiesForGovernorate(governorate?: string): string[] {
  const canonical = matchGovernorate(governorate);
  return canonical ? (EGYPT_CITIES[canonical] ?? []) : [];
}

/** The canonical city name within a governorate, or "" when unknown. */
export function matchCity(governorate?: string, value?: string): string {
  const wanted = normalizePlaceName(value);
  if (!wanted) return "";
  return (
    citiesForGovernorate(governorate).find(
      (name) => normalizePlaceName(name) === wanted,
    ) ?? ""
  );
}
